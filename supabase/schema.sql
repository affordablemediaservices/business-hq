create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- Members allow-list: ONLY emails listed here can read or write data.
-- ---------------------------------------------------------------------
create table if not exists public.members (
  id            uuid primary key default gen_random_uuid(),
  email         text not null unique,
  display_name  text not null,
  side          text not null check (side in ('Developer','Pierre')),
  leads_access  boolean not null default false,
  created_at    timestamptz not null default now()
);

create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members
                 where lower(email) = lower(coalesce(auth.jwt() ->> 'email','')));
$$;

create or replace function public.has_leads_access() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members
                 where lower(email) = lower(coalesce(auth.jwt() ->> 'email',''))
                   and leads_access);
$$;

