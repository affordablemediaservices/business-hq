-- ---------------------------------------------------------------------
-- Security: Row Level Security on every table
-- (Supabase no longer exposes new tables automatically since 30 Oct 2026,
--  so the GRANTs further down are required — keep them.)
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['projects','workflows','tasks','requests','content','ideas',
                           'documents','comments','activity','reports'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "members full access" on public.%I', t);
    execute format('create policy "members full access" on public.%I for all to authenticated
                    using (public.is_member()) with check (public.is_member())', t);
  end loop;
end $$;

-- Leads: only members with leads_access = true
alter table public.leads enable row level security;
drop policy if exists "leads access" on public.leads;
create policy "leads access" on public.leads for all to authenticated
  using (public.has_leads_access()) with check (public.has_leads_access());

-- Members: members can see the list; nobody can change it from the website
alter table public.members enable row level security;
drop policy if exists "members can read" on public.members;
create policy "members can read" on public.members for select to authenticated
  using (public.is_member());

grant usage on schema public to authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.is_member(), public.has_leads_access() to authenticated;
revoke execute on function public.is_member(), public.has_leads_access() from anon;
revoke all on public.members from anon;

-- ---------------------------------------------------------------------
-- File attachments (private bucket, members only)
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('attachments', 'attachments', false)
on conflict (id) do nothing;

drop policy if exists "members manage attachments" on storage.objects;
create policy "members manage attachments" on storage.objects for all to authenticated
  using (bucket_id = 'attachments' and public.is_member())
  with check (bucket_id = 'attachments' and public.is_member());

